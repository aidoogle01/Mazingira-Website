"""Download Mazingira's own photos into site/src/assets/photos/ and write a manifest.

    python3 tools/fetch_photos.py

Only images Mazingira uploaded to Wix (media IDs starting `1ac0ef_`) are fetched; Wix stock (`11062b_`)
and third-party badges are skipped. Sources: every image referenced in content/ plus the team photos.
The manifest (site/src/assets/photos/manifest.json) maps each original URL to its local file and alt text.
"""
import json, os, re, glob, urllib.request
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'site/src/assets/photos')
OWN = re.compile(r'https://static\.wixstatic\.com/media/(1ac0ef_[0-9a-f]+~mv2\.(?:jpe?g|png|webp))', re.I)
SKIP_ALT = re.compile(r'logo|trip ?advisor|tato', re.I)
MAX = 2000  # px, longest side: enough for a full-screen hero; Astro makes the smaller sizes

# Some of Mazingira's uploads are not their photographs: old route-map graphics, and lodge marketing
# photos that belong to the lodges (link to those, don't show them). Classify by alt text.
def kind(alt):
    a = (alt or '').lower()
    if 'map' in a.split() or a.startswith('map of'):
        return 'map-graphic'
    if re.search(r'\b(lodge|hotel|meli[aá]|serena|resort|pool area|camp exterior|exterior)\b', a):
        return 'lodge'
    return 'photo'

# Team photos are in the old Meet the Team page in roster order (see design/system/assets/Team/README.md).
TEAM = {
    'jacob-s-kereiya': ('1ac0ef_adf9e5b411a04350a090ad96423699b7~mv2.jpg', 'Jacob S. Kereiya beside a Mazingira spare-wheel cover'),
    'goodluck-nathan': ('1ac0ef_2de65a7dfebf4afb9a13f210ed56c75f~mv2.jpg', 'Goodluck Nathan on the roof of a Mazingira safari vehicle'),
    'team': ('1ac0ef_19129683663c48cbaa99237150fd5f99~mv2.webp', 'The Mazingira team in khaki uniforms on and around two branded Land Cruisers'),
}

# Mazingira's own gallery photos from the old homepage (also in the design system's Photos group).
GALLERY = {
    '1ac0ef_1aa4630866284fad84ec60a2b72fc68e~mv2.jpg': 'A herd of elephants walking through dry grass in Tarangire',
    '1ac0ef_2c70ca514e524c8790facd8f0c6460a1~mv2.png': 'A dinner table set beside a campfire at dusk',
    '1ac0ef_3d3287c1a3954a1c8ebc92fa142e5be2~mv2.png': 'An acacia silhouetted against a pink sky over the savannah',
    '1ac0ef_914921ce50b841fd9201f83163329c0d~mv2.png': 'A Mazingira Land Cruiser on a dirt track under a big sky',
    '1ac0ef_78de39843baa4a84b53a275e19cbc634~mv2.jpg': 'A leopard lying on a rock',
    '1ac0ef_fc18612c1892476b9ce66dad2a69a6b6~mv2.jpg': 'A male lion resting in green grass',
    '1ac0ef_7230438675cc4fc8a8d04505323a3cf7~mv2.jpg': 'Two giraffes beside a tree',
    '1ac0ef_5ab8ed44d5e14d48b4b75485f720630d~mv2.png': 'A canvas safari tent under acacia trees',
}

def collect():
    want = {}
    for f in glob.glob(os.path.join(ROOT, 'content/**/*.json'), recursive=True):
        doc = json.load(open(f))
        for im in (doc.get('images') or []) if isinstance(doc, dict) else []:
            m = OWN.match(im.get('src', ''))
            if m and not SKIP_ALT.search(im.get('alt') or ''):
                want.setdefault(m.group(1), im.get('alt') or '')
    for key, (media, alt) in TEAM.items():
        want[media] = alt
    for media, alt in GALLERY.items():
        want.setdefault(media, alt)
    return want

def main():
    os.makedirs(OUT, exist_ok=True)
    manifest = {}
    for media, alt in sorted(collect().items()):
        local = media.replace('~mv2', '')
        path = os.path.join(OUT, local)
        url = f'https://static.wixstatic.com/media/{media}'
        local = re.sub(r'\.(png|webp|jpeg)$', '.jpg', local, flags=re.I)
        path = os.path.join(OUT, local)
        if not os.path.exists(path):
            raw = path + '.download'
            urllib.request.urlretrieve(url, raw)
            im = Image.open(raw).convert('RGB')
            im.thumbnail((MAX, MAX))
            im.save(path, quality=84, optimize=True, progressive=True)
            os.remove(raw)
        w, h = Image.open(path).size
        k = 'graphic' if w / h > 5 else kind(alt)   # icon strips and banners of logos, not photographs
        manifest[url] = {'file': local, 'alt': alt, 'kind': k, 'width': w, 'height': h}
    team = {k: re.sub(r'\.(png|webp|jpeg)$', '.jpg', TEAM[k][0].replace('~mv2', ''), flags=re.I) for k in TEAM}
    json.dump({'note': 'Generated by tools/fetch_photos.py. Mazingira-owned images only.', 'images': manifest, 'team': team},
              open(os.path.join(OUT, 'manifest.json'), 'w'), indent=2)
    print(f'{len(manifest)} photos in {os.path.relpath(OUT, ROOT)}')

if __name__ == '__main__':
    main()
